def widgets(source):
 stack=[];items={}
 for line in source.splitlines():
  s=line.strip()
  if s.startswith('Begin Object'):
   path=re.search(r'ExportPath="[^\']*\'([^\']+)\'',s);stack.append((path.group(1) if path else '',[]))
  elif s=='End Object':
   path,own=stack.pop()
   if ':WidgetTree' in path:items[path]=own
  elif stack:stack[-1][1].append(s)
 return items
