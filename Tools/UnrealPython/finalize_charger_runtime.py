"""Finalize editable charger defaults after installing its Blueprint graphs."""
import unreal
ROOT='/Game/ThirdPerson/Blueprints/EnemigoIA/'
tree=unreal.load_asset(ROOT+'BT_Charger')
bb=unreal.load_asset(ROOT+'BB_Charger')
lib=unreal.get_default_object(unreal.SystemLibrary.static_class())
tree.modify()
lib.call_method('SetObjectPropertyByName',(tree,'BlackboardAsset',bb))
root=unreal.find_object(None,tree.get_path_name()+':Behavior Tree.BehaviorTreeGraphNode_Root_0')
lib.call_method('SetObjectPropertyByName',(root,'BlackboardAsset',bb))
move=unreal.find_object(None,tree.get_path_name()+':Instance_13')
key=move.get_editor_property('BlackboardKey')
key.set_editor_property('SelectedKeyName','TargetActor')
key.set_editor_property('SelectedKeyType',unreal.load_class(None,'/Script/AIModule.BlackboardKeyType_Object'))
key.set_editor_property('SelectedKeyID',0)
move.set_editor_property('BlackboardKey',key)
radius=move.get_editor_property('AcceptableRadius');radius.set_editor_property('DefaultValue',450.0);move.set_editor_property('AcceptableRadius',radius)
for name in ['bReachTestIncludesAgentRadius','bReachTestIncludesGoalRadius','bAllowPartialPath']:
    value=move.get_editor_property(name);value.set_editor_property('DefaultValue',False);move.set_editor_property(name,value)
cooldown=unreal.find_object(None,tree.get_path_name()+':BTDecorator_Cooldown_0')
value=cooldown.get_editor_property('CoolDownTime');value.set_editor_property('DefaultValue',2.0)
cooldown.set_editor_property('CoolDownTime',value)
unreal.EditorAssetLibrary.save_loaded_asset(tree,only_if_is_dirty=False)
bp=unreal.load_asset(ROOT+'BP_ChargerEnemy')
unreal.BlueprintEditorLibrary.compile_blueprint(bp)
cdo=unreal.get_default_object(bp.generated_class())
cdo.set_editor_property('ai_controller_class',unreal.load_class(None,ROOT+'BP_ChargerController.BP_ChargerController_C'))
cdo.set_editor_property('auto_possess_ai',unreal.AutoPossessAI.PLACED_IN_WORLD_OR_SPAWNED)
cdo.set_editor_property('tags',['Enemy.Charger'])
cdo.mesh.set_skeletal_mesh_asset(unreal.load_asset('/Game/SciFiWarrior02/Meshes/SK_SciFiWarrior02'))
cdo.mesh.set_editor_property('override_materials',[])
cdo.mesh.set_anim_instance_class(unreal.load_class(None,ROOT+'ABP_EnemyEntrega.ABP_EnemyEntrega_C'))
cdo.mesh.set_editor_property('relative_location',unreal.Vector(0,0,-88))
cdo.mesh.set_editor_property('relative_rotation',unreal.Rotator(pitch=0,yaw=-90,roll=0))
cdo.mesh.set_relative_scale3d(unreal.Vector(1,1,1))
unreal.EditorAssetLibrary.save_loaded_asset(bp,only_if_is_dirty=False)
unreal.log('CHARGER_RUNTIME_CONFIGURED')
